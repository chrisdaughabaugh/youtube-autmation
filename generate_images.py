def generate_image_gemini(label: str, prompt: str, api_key: str) -> bool:
    filepath = OUTPUT_DIR / f"{label}.jpg"
    url = (
        "https://generativelanguage.googleapis.com/v1beta/"
        f"models/gemini-2.5-flash-image:generateContent?key={api_key}"
    )
    payload = {
        "contents": [{"parts": [{"text": f"Generate an image: {prompt}"}]}],
        "generationConfig": {"responseModalities": ["IMAGE"]},
    }
    try:
        resp = requests.post(url, json=payload, timeout=120)
        if resp.status_code in (429, 400):
            return False
        resp.raise_for_status()
        parts = resp.json()["candidates"][0]["content"]["parts"]
        for part in parts:
            if "inlineData" in part:
                filepath.write_bytes(base64.b64decode(part["inlineData"]["data"]))
                return True
    except Exception:
        pass
    return False


def generate_image_pollinations(label: str, prompt: str) -> bool:
    import urllib.request, urllib.parse
    filepath = OUTPUT_DIR / f"{label}.jpg"
    encoded  = urllib.parse.quote(prompt[:500])   # cap length
    # Try free Pollinations models in order
    for model in ["turbo", "flux-schnell", "stable-diffusion-xl-base-1.0"]:
        url = (f"https://image.pollinations.ai/prompt/{encoded}"
               f"?width=1792&height=1024&model={model}&nologo=true")
        for attempt in range(1, 3):
            try:
                req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
                with urllib.request.urlopen(req, timeout=90) as r:
                    data = r.read()
                filepath.write_bytes(data)
                time.sleep(10)
                return True
            except Exception as e:
                err = str(e)
                if "402" in err:
                    print(f"    Pollinations/{model} requires payment - trying next model...")
                    break   # skip remaining attempts for this model
                print(f"    Pollinations/{model} attempt {attempt} failed: {e}")
                if attempt < 2:
                    time.sleep(20)
    return False


def generate_image_huggingface(label: str, prompt: str) -> bool:
    """Free fallback via Hugging Face Inference API — no key required for public models."""
    filepath = OUTPUT_DIR / f"{label}.jpg"
    url = "https://api-inference.huggingface.co/models/stabilityai/stable-diffusion-xl-base-1.0"
    for attempt in range(1, 4):
        try:
            resp = requests.post(url, json={"inputs": prompt[:300],
                                 "parameters": {"width": 1024, "height": 576}}, timeout=120)
            if resp.status_code == 503:
                print(f"    HuggingFace model loading, waiting 20s...")
                time.sleep(20)
                continue
            resp.raise_for_status()
            filepath.write_bytes(resp.content)
            return True
        except Exception as e:
            print(f"    HuggingFace attempt {attempt} failed: {e}")
            if attempt < 3:
                time.sleep(15)
    return False


def generate_image(label: str, prompt: str, api_key: str) -> None:
    filepath = OUTPUT_DIR / f"{label}.jpg"
    if filepath.exists():
        print(f"  Skipping (already exists): {filepath}")
        return
    print(f"Generating: {label}")
    if generate_image_gemini(label, prompt, api_key):
        print(f"  Saved (Gemini): {filepath}")
        time.sleep(3)
    elif generate_image_pollinations(label, prompt):
        print(f"  Saved (Pollinations fallback): {filepath}")
    elif generate_image_huggingface(label, prompt):
        print(f"  Saved (HuggingFace fallback): {filepath}")
    else:
        print(f"  WARNING: all image sources failed for {label} — pipeline will continue")


def main():
    api_key = load_api_key()

    prompts = PROMPTS
    prompts_file = Path("output/image_prompts.json")
    if prompts_file.exists():
        prompts = json.loads(prompts_file.read_text(encoding="utf-8"))
        print(f"Loaded {len(prompts)} image prompts from output/image_prompts.json")

    print(f"Generating {len(prompts)} images into '{OUTPUT_DIR}/'...\n")
    for item in prompts:
        generate_image(item["label"], item["prompt"], api_key)
    print("\nDone.")


if __name__ == "__main__":
    main()
